/**
 * @param {Buffer}  docxBuffer  the COMPOSED agreement .docx
 * @param {object}  meta        { reference, versionLabel, participantName,
 *                                statusLabel, generatedAt }
 * @param {boolean} lockProviderFields  true for an ISSUED agreement, false for
 *                  a manual blank form
 * @returns {Promise<{bytes: Buffer, pageCount, fieldCount, fieldNames, warnings}>}
 */
async function renderAgreementPdf({ docxBuffer, meta = {}, lockProviderFields = false }) {
  const outline = await outlineFromDocx(docxBuffer);

  const pdf = await PDFDocument.create();
  pdf.setTitle(`Service Agreement ${meta.reference || ''}`.trim());
  pdf.setAuthor('Opal Therapy');
  pdf.setSubject('NDIS Service Agreement');
  pdf.setProducer('Opal Therapy Portal');
  pdf.setCreator('Opal Therapy Portal');
  pdf.setLanguage('en-AU');

  const fonts = {
    regular: await pdf.embedFont(StandardFonts.Helvetica),
    bold: await pdf.embedFont(StandardFonts.HelveticaBold),
    italic: await pdf.embedFont(StandardFonts.HelveticaOblique),
  };

  const flow = new Flow(pdf, fonts, {
    headerLeft: 'NDIS SERVICE AGREEMENT',
    headerRight: meta.reference || '',
    footerLeft: [
      meta.participantName, meta.reference,
      meta.versionLabel ? `Template v${meta.versionLabel}` : null,
    ].filter(Boolean).join('  ·  '),
  });

  renderBlocks(flow, outline.blocks, { lockProviderFields });
  flow.finish();

  // Appearance streams AND NeedAppearances — see the file header for why both.
  try {
    flow.form.updateFieldAppearances(fonts.regular);
  } catch (err) {
    flow.warnings.push(`Field appearances could not be pre-generated: ${err.message}`);
  }
  flow.form.acroForm.dict.set(PDFName.of('NeedAppearances'), PDFBool.True);

  const bytes = Buffer.from(await pdf.save({ updateFieldAppearances: false }));

  return {
    bytes,
    pageCount: flow.pages.length,
    fieldCount: flow.form.getFields().length,
    fieldNames: flow.names.slice(),
    warnings: [...outline.warnings, ...flow.warnings],
  };
}

/** `Opal_Service_Agreement_<Participant>_<REF>.pdf` */
function agreementFilename(meta = {}, suffix = '') {
  const parts = ['Opal_Service_Agreement'];
  if (meta.participantName) parts.push(sanitiseFilenamePart(meta.participantName, 50));
  if (meta.reference) parts.push(sanitiseFilenamePart(meta.reference, 24));
  if (suffix) parts.push(sanitiseFilenamePart(suffix, 20));
  return `${parts.filter(Boolean).join('_')}.pdf`;
}

