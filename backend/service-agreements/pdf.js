'use strict';

/**
 * SERVICE AGREEMENT — FILLABLE PDF
 *
 *   renderAgreementPdf({ docxBuffer, meta, lockProviderFields })
 *     → { bytes, pageCount, fieldCount, fieldNames, warnings }
 *
 * Renders the COMPOSED Word document (via ./docx-outline.js) as a standard
 * AcroForm PDF: prefilled values are drawn as text, blank controls become
 * interactive widgets, and the two documents cannot disagree because there is
 * only one document — this reads the same bytes Word would open.
 *
 * ── ACROFORM, NOT XFA ──────────────────────────────────────────────────────
 * pdf-lib emits AcroForm only; there is no XFA code path to avoid. That is the
 * right format anyway: XFA is deprecated, unsupported in browser viewers and
 * in macOS Preview, and a participant who cannot open the form cannot sign it.
 *
 * ── WHAT "COMPATIBLE" HONESTLY MEANS ───────────────────────────────────────
 * Every field carries a real appearance stream, generated by pdf-lib against
 * the same standard font the layout was measured with, AND the document sets
 * /NeedAppearances true. Belt and braces, because the two failure modes are
 * opposite: a viewer that ignores appearance streams (some browser viewers)
 * needs NeedAppearances to render a value at all, while a viewer that honours
 * NeedAppearances but regenerates poorly (older Acrobat) needs the stream to
 * fall back to. Tested against Chrome/Firefox PDF viewing, Adobe Acrobat
 * Reader and macOS Preview on a best-effort basis — NOT a claim about every
 * PDF application in existence.
 *
 * ── FONTS ──────────────────────────────────────────────────────────────────
 * The standard 14 (Helvetica family), so no font is embedded and every viewer
 * has them. The cost is WinAnsi: characters outside CP1252 cannot be drawn and
 * pdf-lib throws on them. toWinAnsi() transliterates what it can — including
 * the Latin Extended-A block, so a participant called Zoë, Ngātai or Nguyễn
 * reads as close to their name as the encoding permits — and substitutes '?'
 * for scripts it cannot represent. That limitation is recorded rather than
 * hidden; fixing it properly means embedding a Unicode face with fontkit.
 * This is the same trade-off, and the same helper, as interview-pdf.js.
 *
 * ── SIGNATURES ─────────────────────────────────────────────────────────────
 * A signature field here is a TEXT field on a signature rule, not a
 * cryptographic signature field. Nothing in this pipeline can produce or
 * validate a PKCS#7 signature, and labelling a typed name as a digital
 * signature would be a false assurance in a legal document. The portal signing
 * route records intent, capacity, timestamp and a document hash; that is what
 * is claimed, and it is claimed in those words.
 */

