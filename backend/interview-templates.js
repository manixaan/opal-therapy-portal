'use strict';

/**
 * INTERVIEW PREPARATION — TEMPLATE CATALOGUE
 *
 * One schema shape for every structured interview the practice runs. A
 * template says what is ASKED and in what order; it holds no candidate data
 * and no policy. Everything downstream — the online form, the blank fillable
 * PDF, the populated PDF and the stored record's own snapshot — is rendered
 * from this one declaration, so a question can never say one thing on screen
 * and another on paper.
 *
 * ── Why the catalogue is code, not database rows ───────────────────────────
 * The same reasoning as the interactive induction's module catalogue
 * (induction-modules.js) and the assessment framework's definitions.js: an
 * interview template is AUTHORED CONTENT. It belongs in version control where
 * a change is reviewable, diffable and revertible, and where the wording that
 * shipped on a given date is recoverable from git. A templates table would
 * make the question wording an operational value that no review ever sees.
 *
 * Adding a template is therefore a file edit and one line in TEMPLATES below —
 * no migration, no redesign, no new route. The listed-but-unbuilt roles in
 * FUTURE_TEMPLATES exist to make that extension point explicit.
 *
 * ── Versioning, and why records snapshot rather than reference ─────────────
 * Every template carries an integer `version`. When an interview record is
 * created the ENTIRE resolved template is frozen into the record's
 * `template_schema` column. Editing this file afterwards never changes a
 * question a candidate was actually asked, never re-labels a stored answer and
 * never alters a PDF regenerated from an old record. That is the same pinning
 * rule learning_assignments applies via workflow_version_id, expressed as a
 * snapshot because the source of truth here is a file rather than a row.
 *
 * ── The question grammar ───────────────────────────────────────────────────
 * A section holds questions. A question has a `type` from FIELD_TYPES, and
 * every renderer switches on exactly that set:
 *
 *   text          one-line value (candidate name, a date typed as text)
 *   date          one-line ISO-ish date value
 *   longtext      a narrative answer. UNBOUNDED — no maxlength anywhere in
 *                 this system, on screen or in the PDF (see MAX_ANSWER_CHARS
 *                 for the single storage-sanity ceiling, which is far beyond
 *                 any real answer).
 *   checkboxes    zero or more of `options`
 *   choice        exactly one of `options`; an option may carry
 *                 `detail: true`, which reveals a free-text follow-up
 *   ratings       a labelled grid: `rows` scored on `scale`
 *
 * `rows` on a longtext is a STARTING height for the textarea and the PDF's
 * blank field. It is never a limit: the textarea grows and the PDF reflows.
 */

// ─────────────────────────────────────────────────────────────────────────────
//  Vocabulary
// ─────────────────────────────────────────────────────────────────────────────

const FIELD_TYPES = ['text', 'date', 'longtext', 'checkboxes', 'choice', 'ratings'];

/** Narrative types whose answers are free text of any practical length. */
const NARRATIVE_TYPES = ['text', 'date', 'longtext'];

/**
 * The one storage ceiling, applied per answer at the API boundary.
 *
 * It is NOT a UX limit and must never be presented as one: 200 000 characters
 * is roughly 35 000 words, or about eighty pages of typing in a single answer
 * box. Its only job is to stop a scripted client putting a megabyte into a
 * JSONB column. A person conducting an interview will never meet it.
 */
const MAX_ANSWER_CHARS = 200000;

const STATUSES = ['draft', 'in_progress', 'completed', 'archived'];

/** The rating scale every template shares today. */
const RATING_SCALE = [1, 2, 3, 4, 5];

const RATING_GUIDE = '1 = significant concerns, 3 = developing / acceptable with support, 5 = strong evidence.';

