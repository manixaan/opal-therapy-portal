/** Walk every question in a template (or a stored snapshot), in document order. */
function eachQuestion(template, fn) {
  (template.sections || []).forEach((section) => {
    (section.questions || []).forEach((q) => fn(q, section));
    (section.signoff || []).forEach((q) => fn(q, section));
  });
}

/** questionKey → question, for a template or a stored snapshot. */
function questionIndex(template) {
  const index = new Map();
  eachQuestion(template, (q) => index.set(q.key, q));
  return index;
}

/** The library card the Interview Preparation landing page renders. */
function catalogueEntry(t) {
  const sections = t.sections || [];
  let questionCount = 0;
  eachQuestion(t, () => { questionCount += 1; });
  return {
    key: t.key,
    version: t.version,
    name: t.name,
    documentTitle: t.documentTitle,
    category: t.category,
    discipline: t.discipline,
    summary: t.summary,
    tags: t.tags || [],
    approxPages: t.approxPages,
    defaultPosition: t.defaultPosition,
    sectionCount: sections.length,
    questionCount,
    available: true,
    sections: sections.map((s) => ({
      key: s.key, number: s.number, title: s.title, shortTitle: s.shortTitle || s.title,
    })),
  };
}

function catalogue() {
  return {
    templates: TEMPLATES.map(catalogueEntry),
    upcoming: FUTURE_TEMPLATES.map((t) => ({ ...t, available: false })),
  };
}

/**
 * The frozen copy stored on a record. A deep clone, because the record must
 * never share structure with the live module — a later mutation of TEMPLATES
 * (in a test, say) must not reach into an already-created record.
 */
function snapshotOf(template) {
  return JSON.parse(JSON.stringify(template));
}

// ─────────────────────────────────────────────────────────────────────────────
//  Answer coercion
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Coerce one submitted answer to the shape its question type stores, or return
 * `undefined` for anything the type cannot hold. Unknown question keys and
 * malformed values are DROPPED rather than stored — a responses blob is
 * rendered back into a document, so it may only ever contain what the
 * template's own grammar describes.
 *
 * Stored shapes:
 *   text | date | longtext   string
 *   checkboxes               string[] of option keys, template order, unique
 *   choice                   { option: string, detail?: string }
 *   ratings                  { rowKey: number }  — values from `scale` only
 */
function coerceAnswer(question, value) {
  if (!question) return undefined;

  if (NARRATIVE_TYPES.includes(question.type)) {
    if (value === null || value === undefined) return '';
    if (typeof value === 'number' || typeof value === 'boolean') return String(value);
    if (typeof value !== 'string') return undefined;
    // No trim of interior content: paragraph breaks and indentation are the
    // interviewer's, and the PDF reproduces them. Only the storage ceiling.
    return value.length > MAX_ANSWER_CHARS ? value.slice(0, MAX_ANSWER_CHARS) : value;
  }

  if (question.type === 'checkboxes') {
    if (!Array.isArray(value)) return undefined;
    const valid = new Set((question.options || []).map((o) => o.key));
    const chosen = new Set(value.filter((v) => typeof v === 'string' && valid.has(v)));
    return (question.options || []).map((o) => o.key).filter((k) => chosen.has(k));
  }

  if (question.type === 'choice') {
    if (value === null || value === undefined || value === '') return { option: null, detail: '' };
    const raw = typeof value === 'string' ? { option: value } : value;
    if (!raw || typeof raw !== 'object') return undefined;
    const option = (question.options || []).find((o) => o.key === raw.option);
    if (!option) return { option: null, detail: '' };
    let detail = '';
    if (option.detail && typeof raw.detail === 'string') {
      detail = raw.detail.length > MAX_ANSWER_CHARS ? raw.detail.slice(0, MAX_ANSWER_CHARS) : raw.detail;
    }
    return { option: option.key, detail };
  }

  if (question.type === 'ratings') {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return undefined;
    const scale = new Set(question.scale || RATING_SCALE);
    const out = {};
    (question.rows || []).forEach((row) => {
      const n = Number(value[row.key]);
      if (Number.isFinite(n) && scale.has(n)) out[row.key] = n;
    });
    return out;
  }

  return undefined;
}

/**
 * Coerce a whole responses object against a template snapshot. Returns only
 * keys the template defines; everything else is discarded silently, because a
 * client sending an unknown key is a bug or an attack, never a lost answer.
 */
function coerceResponses(template, submitted) {
  const out = {};
  if (!submitted || typeof submitted !== 'object') return out;
  const index = questionIndex(template);
  Object.keys(submitted).forEach((key) => {
    const q = index.get(key);
    if (!q) return;
    const coerced = coerceAnswer(q, submitted[key]);
    if (coerced !== undefined) out[key] = coerced;
  });
  return out;
}

/** True when an answer holds nothing a reader would see. */
function isAnswerEmpty(question, value) {
  if (value === undefined || value === null) return true;
  if (!question) return true;
  if (NARRATIVE_TYPES.includes(question.type)) return String(value).trim() === '';
  if (question.type === 'checkboxes') return !Array.isArray(value) || value.length === 0;
  if (question.type === 'choice') return !value.option;
  if (question.type === 'ratings') return !value || Object.keys(value).length === 0;
  return true;
}

/**
 * Completion progress over a template snapshot: how many questions carry an
 * answer. Used for the record list's progress column and for the "some
 * questions are blank" warning shown when completing — never to BLOCK
 * completion, because an interview note is allowed to be partial.
 */
function progressOf(template, responses) {
  let total = 0;
  let answered = 0;
  const blank = [];
  eachQuestion(template, (q, section) => {
    total += 1;
    if (isAnswerEmpty(q, (responses || {})[q.key])) blank.push({ key: q.key, label: q.label, section: section.title });
    else answered += 1;
  });
  return { total, answered, blank, percent: total ? Math.round((answered / total) * 100) : 0 };
}

