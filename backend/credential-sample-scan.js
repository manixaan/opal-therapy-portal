/**
 * SAMPLE CREDENTIAL SCANS — demonstration documents, and nothing else.
 *
 * The credentials register now expects every credential to carry the document
 * behind it. Credentials that pre-date that rule have nothing attached, and a
 * demonstration or training environment full of "scan missing" badges shows
 * the feature at its least useful — nobody can see what a filed certificate
 * looks like, what the reader does with it, or what Verify now means.
 *
 * So this generates a stand-in: a one-page PDF laid out like a certificate,
 * carrying the values already on the credential record.
 *
 * ── WHY IT IS DELIBERATELY UNMISTAKABLE ────────────────────────────────────
 * A convincing facsimile of an AHPRA certificate or a WWCC card is a forgery
 * template. It does not become one when somebody misuses it later; it is one
 * the moment it is convincing. Every page this produces therefore carries:
 *
 *   - a repeated diagonal SPECIMEN watermark across the whole page,
 *   - a red-ruled statement, above the fold, that it is not genuine,
 *   - the generating system named on the page,
 *   - no issuer crest, seal, signature, hologram or logo of any kind.
 *
 * None of that is decoration and none of it is optional. A caller that wants
 * these removed wants a different thing from a different tool.
 *
 * The real replacement is the holder uploading their actual certificate,
 * which is what the Credentials surface asks for. This exists so the surface
 * can be seen working before they do.
 */

const { PDFDocument, StandardFonts, rgb, degrees } = require('pdf-lib');

const A4 = Object.freeze({ width: 595.28, height: 841.89 });

const INK = rgb(0.11, 0.13, 0.15);
const SOFT = rgb(0.42, 0.45, 0.49);
const RULE = rgb(0.82, 0.84, 0.86);
const ALERT = rgb(0.72, 0.15, 0.15);
const WATERMARK = rgb(0.90, 0.91, 0.93);

