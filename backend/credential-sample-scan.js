const NOT_GENUINE = 'SPECIMEN — NOT A GENUINE CREDENTIAL';

const DISCLAIMER = [
  'This page is demonstration data generated by the Opal practice portal. It is',
  'not a certificate, it was not issued by the body named above, and it evidences',
  'nothing. It must not be presented as proof of registration, clearance, training',
  'or insurance. Replace it by uploading the real document.',
];

/** 1 May 2029, from a Date or an ISO string. Blank when there is no date. */
function formatDate(value) {
  if (!value) return '—';
  const d = value instanceof Date ? value : new Date(`${String(value).slice(0, 10)}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return '—';
  const months = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];
  return `${d.getUTCDate()} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

/** pdf-lib's WinAnsi fonts throw on characters they cannot encode — a curly
 *  apostrophe out of a database is enough. Nothing here is worth an exception. */
function ascii(value, fallback = '') {
  const s = String(value == null ? '' : value)
    .replace(/[‘’‛]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/[^\x20-\x7E]/g, '');
  return s.trim() || fallback;
}

/**
 * Build the sample scan for one credential.
 *
 * @param {object} credential            the credential record (or its fields)
 * @param {string} credential.credential_type
 * @param {string} credential.credential_name
 * @param {string} [credential.issuing_body]
 * @param {string} [credential.registration_number]
 * @param {Date|string} [credential.issue_date]
 * @param {Date|string} [credential.expiry_date]
 * @param {string} [holderName]          who the specimen names as the holder
 * @returns {Promise<Buffer>} a one-page PDF
 */
async function buildSampleScan(credential = {}, holderName = '') {
  const style = PRESENTATION[credential.credential_type] || PRESENTATION.other;

  const pdf = await PDFDocument.create();
  pdf.setTitle(`${NOT_GENUINE} — ${ascii(credential.credential_name, 'Credential')}`);
  pdf.setSubject('Demonstration data generated by the Opal practice portal. Not a genuine credential.');
  pdf.setProducer('Opal practice portal — sample credential generator');
  pdf.setCreator('Opal practice portal — sample credential generator');

  const page = pdf.addPage([A4.width, A4.height]);
  const body = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  // ── The watermark goes down FIRST, so every value sits on top of it and no
  //    crop of this page is free of it. ─────────────────────────────────────
  for (let row = -1; row < 7; row += 1) {
    for (let col = -1; col < 3; col += 1) {
      page.drawText('SPECIMEN', {
        x: 40 + col * 230,
        y: 60 + row * 130 + col * 40,
        size: 34,
        font: bold,
        color: WATERMARK,
        rotate: degrees(30),
      });
    }
  }

  let y = A4.height - 70;

  // ── The disclaimer sits ABOVE the certificate, not in a footer. A reader
  //    who sees only the top of the page still sees it. ────────────────────
  page.drawRectangle({
    x: 56, y: y - 76, width: A4.width - 112, height: 82,
    borderColor: ALERT, borderWidth: 1.2, color: rgb(1, 0.97, 0.97),
  });
  page.drawText(NOT_GENUINE, { x: 68, y: y - 8, size: 12, font: bold, color: ALERT });
  DISCLAIMER.forEach((line, i) => {
    page.drawText(line, { x: 68, y: y - 26 - i * 12, size: 8, font: body, color: ALERT });
  });

  y -= 130;

  // ── The certificate proper ───────────────────────────────────────────────
  page.drawText(ascii(credential.issuing_body || style.issuer, style.issuer).toUpperCase(), {
    x: 56, y, size: 10, font: bold, color: SOFT,
  });
  y -= 34;

  page.drawText(ascii(style.heading), { x: 56, y, size: 22, font: bold, color: INK });
  y -= 20;
  page.drawText(ascii(credential.credential_name, 'Credential'), {
    x: 56, y, size: 13, font: body, color: SOFT,
  });

  y -= 26;
  page.drawLine({
    start: { x: 56, y }, end: { x: A4.width - 56, y }, thickness: 1, color: RULE,
  });

  y -= 40;
  page.drawText('This is to certify that', { x: 56, y, size: 10, font: body, color: SOFT });
  y -= 26;
  page.drawText(ascii(holderName, 'Name not recorded'), { x: 56, y, size: 18, font: bold, color: INK });
  y -= 22;
  page.drawText('holds the credential described below.', { x: 56, y, size: 10, font: body, color: SOFT });

  y -= 46;
  const rows = [
    [style.numberLabel, ascii(credential.registration_number, 'Not recorded')],
    ['Issued', formatDate(credential.issue_date)],
    [credential.expiry_date ? 'Expires' : style.periodLabel,
      credential.expiry_date ? formatDate(credential.expiry_date) : 'No expiry recorded'],
    ['Status', 'Specimen — carries no status'],
  ];
  for (const [label, value] of rows) {
    page.drawText(ascii(label), { x: 56, y, size: 9, font: bold, color: SOFT });
    page.drawText(ascii(value), { x: 210, y, size: 11, font: body, color: INK });
    y -= 14;
    page.drawLine({
      start: { x: 56, y: y + 4 }, end: { x: A4.width - 56, y: y + 4 },
      thickness: 0.5, color: RULE,
    });
    y -= 14;
  }

  // ── Where a real certificate carries a signature and a seal, this says why
  //    it does not. ──────────────────────────────────────────────────────────
  y -= 40;
  page.drawText('No signature, seal or issuer mark appears on this page, by design.', {
    x: 56, y, size: 9, font: body, color: SOFT,
  });
  y -= 13;
  page.drawText('A convincing copy of an identity document is a forgery template.', {
    x: 56, y, size: 9, font: body, color: SOFT,
  });

  page.drawText('Generated by the Opal practice portal as demonstration data.', {
    x: 56, y: 56, size: 8, font: body, color: SOFT,
  });
  page.drawText(NOT_GENUINE, { x: 56, y: 44, size: 8, font: bold, color: ALERT });

  return Buffer.from(await pdf.save());
}

/** A stable, obviously-synthetic file name. */
function sampleFileName(credential = {}) {
  const slug = ascii(credential.credential_type || 'credential')
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'credential';
  return `SPECIMEN-${slug}.pdf`;
}

