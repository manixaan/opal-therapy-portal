/** The CP1252-only code points, i.e. the 0x80–0x9F block's real characters. */
const CP1252_HIGH = [
  0x20AC, 0x201A, 0x0192, 0x201E, 0x2026, 0x2020, 0x2021, 0x02C6, 0x2030,
  0x0160, 0x2039, 0x0152, 0x017D, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022,
  0x2013, 0x2014, 0x02DC, 0x2122, 0x0161, 0x203A, 0x0153, 0x017E, 0x0178,
];
const ENCODABLE = new Set(CP1252_HIGH);
for (let c = 0x20; c <= 0x7E; c += 1) ENCODABLE.add(c);
for (let c = 0xA0; c <= 0xFF; c += 1) ENCODABLE.add(c);

