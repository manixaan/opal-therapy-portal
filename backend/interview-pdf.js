'use strict';

/**
 * INTERVIEW PREPARATION — PDF RENDERER
 *
 * One schema-driven renderer produces both documents the module offers:
 *
 *   mode 'blank'      the fillable template. Every question carries a real
 *                     AcroForm field, so it opens in Preview, Acrobat, Edge
 *                     or Chrome and is typed into like any other form.
 *   mode 'populated'  a stored interview. The same layout, the same fields,
 *                     with the portal's answers already in them — so the
 *                     downloaded document is still editable, and a reviewer
 *                     can annotate it without going back to the portal.
 *
 * ── The rule that shapes everything here ───────────────────────────────────
 * NO ANSWER IS EVER CLIPPED, SHRUNK OR TRUNCATED. The source template gave
 * every question a fixed box, which is why it could not survive a real
 * interview: a three-paragraph answer simply disappeared below the fold. This
 * renderer measures each answer first and sizes its field to the text, and
 * when an answer is taller than the page has left, it SPLITS — the remainder
 * continues in a "Response continued" field on the next page. A six-page
 * template therefore prints as six, eight or fourteen pages depending on what
 * was written, and that is the correct behaviour.
 *
 * Two mechanisms make "never clipped" a guarantee rather than an intention:
 *
 *   1. Measurement is deliberately PESSIMISTIC. Lines are wrapped against
 *      MEASURE_INSET (8pt of side padding), while pdf-lib lays the field's
 *      appearance out against 3.4pt. Wrapping against a narrower column than
 *      the renderer will actually use means pdf-lib can only ever produce the
 *      same number of lines or fewer — never more, which is the direction
 *      that would clip. interview-pdf.test.js proves this against pdf-lib's
 *      own layoutMultilineText rather than trusting the argument.
 *   2. Every field is built one full line taller than its measured text
 *      (SPARE_LINES), so even an unforeseen disagreement about a break point
 *      has somewhere to land — and, in a blank or partly-filled form, the
 *      person typing has room for one more line before the box is full.
 *
 * Beyond that, the field's /V value carries the answer's own text — the
 * renderer stores what the interviewer typed, not a re-flowed copy of it —
 * so the document is recoverable by reading the form rather than by scraping
 * a page. The test suite reads it back and compares it to the input character
 * for character, including the deliberately enormous one.
 *
 * The single exception is a token too wide for the column to hold at all (a
 * pasted URL, a run of underscores). pdf-lib does not break those; it lets
 * them run off the edge. softenLongTokens() inserts the break pdf-lib will
 * not, before anything is measured, so a pathological token wraps instead of
 * escaping the page.
 *
 * ── Fonts, and why user text is transliterated ─────────────────────────────
 * The standard PDF fonts encode WinAnsi (CP1252). An interviewer pasting a
 * candidate's answer can easily bring in a character outside it — a Greek
 * letter, a CJK name, an arrow, an emoji — and pdf-lib THROWS on those rather
 * than dropping them, which would turn "one odd character" into "no document
 * at all". toWinAnsi() therefore transliterates the common cases (→ becomes
 * ->, ≈ becomes ~, a curly quote stays a curly quote because CP1252 has it)
 * and substitutes anything genuinely unrepresentable. Embedding a Unicode
 * font would be the fuller answer; it needs a licensed font binary and the
 * fontkit dependency, and is noted in docs rather than assumed here.
 *
 * ── Branding ───────────────────────────────────────────────────────────────
 * Colours, the teal band, the section bars and the footer are measured from
 * Opal Therapy's own Occupational Therapist Interview Template so a document
 * generated by the portal and one printed from the template look like the
 * same document, because they are.
 */

