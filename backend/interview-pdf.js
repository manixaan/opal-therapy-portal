/**
 * Make a string safe for a standard PDF font without ever throwing.
 * Line endings are normalised here too, so callers only ever deal with '\n'.
 */
function toWinAnsi(value) {
  const s = String(value === null || value === undefined ? '' : value)
    .replace(/\r\n?/g, '\n')
    .replace(/\t/g, '    ');
  let out = '';
  for (const ch of s) {
    if (ch === '\n') { out += ch; continue; }
    const cp = ch.codePointAt(0);
    if (ENCODABLE.has(cp)) { out += ch; continue; }
    if (Object.prototype.hasOwnProperty.call(TRANSLITERATE, ch)) { out += TRANSLITERATE[ch]; continue; }
    // Control characters vanish; anything else leaves a visible placeholder so
    // a reader can see that something was there.
    out += (cp < 0x20 || cp === 0x7F) ? '' : '?';
  }
  return out;
}

/** AcroForm field names are a flat namespace; '.' would create a hierarchy. */
function fieldName(key) {
  return String(key || 'field').replace(/[^A-Za-z0-9_-]/g, '_').slice(0, 90);
}

// ─────────────────────────────────────────────────────────────────────────────
//  Text measurement
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Insert the line breaks pdf-lib will not.
 *
 * pdf-lib's splitOutLines only ever breaks at spaces: a single token wider
 * than the column is emitted whole and runs off the edge of the field. This
 * pass finds those tokens before anything is measured and breaks them at the
 * last character that fits, so wrapping downstream — mine and pdf-lib's alike
 * — has somewhere legal to break. Ordinary prose passes through untouched,
 * which is why the stored answer keeps the interviewer's own line structure.
 */
function softenLongTokens(text, font, size, width) {
  const widthOf = (s) => font.widthOfTextAtSize(s, size);
  // Cheap exit: nothing in this string is long enough to matter.
  if (!/\S{20,}/.test(text)) return text;

  return text.replace(/\S+/g, (token) => {
    if (widthOf(token) <= width) return token;
    let rest = token;
    let out = '';
    while (widthOf(rest) > width) {
      let cut = 1;
      while (cut < rest.length && widthOf(rest.slice(0, cut + 1)) <= width) cut += 1;
      out += `${rest.slice(0, cut)}\n`;
      rest = rest.slice(cut);
    }
    return out + rest;
  });
}

/**
 * Wrap `text` to `width`, honouring existing newlines.
 *
 * Returns `{ source, lines }` where `source` is the WinAnsi-safe, long-token-
 * softened string every offset refers to, and each line is
 * `{ text, start, end }` indexing into it. The offsets are what make a split
 * answer keep the interviewer's own words: a chunk's field value is
 * `source.slice(firstLine.start, lastLine.end)`, which is the ORIGINAL text of
 * those lines — paragraph breaks intact, soft wraps still soft — rather than a
 * re-flowed reconstruction.
 *
 * An empty input yields one empty line, because a blank answer still occupies
 * a row in the layout.
 */
function wrapMeasured(text, font, size, width) {
  const source = softenLongTokens(toWinAnsi(text), font, size, width);
  const widthOf = (s) => font.widthOfTextAtSize(s, size);
  const lines = [];

  let offset = 0;
  const paragraphs = source.split('\n');

  paragraphs.forEach((paragraph, pIndex) => {
    const paraStart = offset;
    offset += paragraph.length + (pIndex < paragraphs.length - 1 ? 1 : 0);

    if (paragraph === '') { lines.push({ text: '', start: paraStart, end: paraStart }); return; }

    const tokens = [];
    const re = /\s+|\S+/g;
    let m;
    while ((m = re.exec(paragraph)) !== null) {
      tokens.push({ text: m[0], start: paraStart + m.index, end: paraStart + m.index + m[0].length });
    }

    let current = '';
    let start = -1;
    let end = -1;
    const flush = () => {
      if (start < 0) return;
      lines.push({ text: current.replace(/\s+$/, ''), start, end });
      current = ''; start = -1; end = -1;
    };

    for (const token of tokens) {
      const isSpace = /^\s+$/.test(token.text);
      if (start < 0 && isSpace) {
        // Leading whitespace on a wrapped line is dropped, as pdf-lib drops it.
        continue;
      }
      const candidate = current + token.text;
      if (widthOf(candidate) <= width || start < 0) {
        if (start < 0) start = token.start;
        current = candidate;
        end = token.end;
        continue;
      }
      flush();
      if (isSpace) continue;
      start = token.start; current = token.text; end = token.end;
    }
    flush();
    // A paragraph of nothing but whitespace still holds a line.
    if (!lines.length || lines[lines.length - 1].end < paraStart) {
      lines.push({ text: '', start: paraStart, end: paraStart + paragraph.length });
    }
  });

  return { source, lines: lines.length ? lines : [{ text: '', start: 0, end: 0 }] };
}

/** The line strings alone — the shape most callers and the tests want. */
function wrapText(text, font, size, width) {
  return wrapMeasured(text, font, size, width).lines.map((l) => l.text);
}

