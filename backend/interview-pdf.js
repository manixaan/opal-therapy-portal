/**
 * A narrative answer, split across as many pages as it needs.
 *
 * Pagination rules, in the order they are applied:
 *   - the question label and at least MIN_SPLIT_LINES of its answer stay
 *     together, so a question is never orphaned at the foot of a page;
 *   - a chunk that will not fit starts a new page rather than being squeezed;
 *   - a continuation is announced ("Response continued"), so a reader always
 *     knows they are still inside the previous question.
 */
function renderNarrative(flow, question, value, mode) {
  const label = question.label || '';
  const guidance = question.guidance || '';
  const answer = mode === 'blank' ? '' : String(value === undefined || value === null ? '' : value);

  const labelH = flow.measureText(label, { size: SIZE_QUESTION, lineHeight: LINE_QUESTION });
  const guideH = guidance
    ? flow.measureText(guidance, { size: SIZE_GUIDE, lineHeight: LINE_GUIDE }) + 2
    : 0;

  const measureWidth = CONTENT_W - MEASURE_INSET;
  const measured = answer
    ? wrapMeasured(answer, flow.font, SIZE_ANSWER, measureWidth)
    : { source: '', lines: [] };
  let lines = measured.lines;

  // A blank (or unanswered) field still needs a box worth writing in: the
  // template's own suggested height, never fewer than three lines.
  const blankLines = Math.max(3, Number(question.rows) || 3);
  if (!lines.length) lines = new Array(blankLines).fill(null);

  const heightFor = (count) => (count + SPARE_LINES) * LINE_ANSWER + FIELD_VPAD * 2;

  // Keep the question with a meaningful piece of its answer.
  const headKeep = labelH + guideH + 6 + heightFor(Math.min(lines.length, MIN_SPLIT_LINES));
  flow.ensure(headKeep);

  flow.text(label, { size: SIZE_QUESTION, lineHeight: LINE_QUESTION, colour: SLATE });
  if (guidance) {
    flow.move(1);
    flow.text(guidance, { size: SIZE_GUIDE, lineHeight: LINE_GUIDE, colour: MUTED, italic: true });
  }
  flow.move(4);

  let remaining = lines;
  let part = 0;

  while (remaining.length) {
    // How many lines can this page still take?
    const room = flow.available;
    let capacity = Math.floor((room - FIELD_VPAD * 2) / LINE_ANSWER) - SPARE_LINES;

    if (capacity < Math.min(remaining.length, MIN_SPLIT_LINES)) {
      flow.newPage();
      if (part > 0) {
        flow.text('Response continued', {
          size: SIZE_GUIDE, lineHeight: LINE_GUIDE, colour: MUTED, italic: true,
        });
        flow.move(3);
      }
      capacity = Math.floor((flow.available - FIELD_VPAD * 2) / LINE_ANSWER) - SPARE_LINES;
    }

    const take = Math.min(remaining.length, Math.max(capacity, 1));
    const chunk = remaining.slice(0, take);
    remaining = remaining.slice(take);

    const height = heightFor(chunk.length);
    // The chunk's OWN text, sliced out of the measured source — not the
    // measured lines rejoined. Soft wraps stay soft, paragraph breaks stay
    // where the interviewer put them, and the field holds what they typed.
    const chunkText = answer && chunk[0]
      ? measured.source.slice(chunk[0].start, chunk[chunk.length - 1].end)
      : '';
    drawAnswerField(flow, {
      name: flow.uniqueName(part === 0 ? question.key : `${question.key}__cont${part + 1}`),
      lines: chunk,
      value: chunkText,
      x: MARGIN_L,
      width: CONTENT_W,
      height,
    });
    flow.move(height + 10);
    part += 1;

    if (remaining.length) {
      flow.newPage();
      flow.text('Response continued', {
        size: SIZE_GUIDE, lineHeight: LINE_GUIDE, colour: MUTED, italic: true,
      });
      flow.move(3);
    }
  }
}

function renderCheckboxes(flow, question, value, mode) {
  const options = question.options || [];
  const chosen = new Set(mode === 'blank' ? [] : (Array.isArray(value) ? value : []));

  const cols = 2;
  const rows = Math.ceil(options.length / cols);
  const colW = CONTENT_W / cols;
  const rowH = 22;

  const labelH = flow.measureText(question.label || '', { size: SIZE_QUESTION, lineHeight: LINE_QUESTION });
  flow.ensure(labelH + 6 + rows * rowH);

  flow.text(question.label || '', { size: SIZE_QUESTION, lineHeight: LINE_QUESTION, colour: SLATE });
  flow.move(6);

  const top = flow.y;
  options.forEach((opt, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    const x = MARGIN_L + col * colW;
    const y = top - row * rowH - CHECK_BOX;
    drawCheckBox(flow, {
      name: flow.uniqueName(`${question.key}__${opt.key}`),
      checked: chosen.has(opt.key),
      x, y,
    });
    flow.page.drawText(toWinAnsi(opt.label), {
      x: x + CHECK_BOX + 8,
      y: y + 1.5,
      size: SIZE_QUESTION,
      font: flow.font,
      color: SLATE,
    });
  });
  flow.move(rows * rowH + 6);
}

/**
 * A single-choice question. Rendered as one AcroForm radio group so the
 * options stay mutually exclusive in a PDF reader too — a set of independent
 * checkboxes would let somebody tick "Progress" and "Do not progress" at once,
 * which is precisely the contradiction the portal's own control prevents.
 */
function renderChoice(flow, question, value, mode) {
  const options = question.options || [];
  const selected = mode === 'blank' ? null : (value && value.option) || null;
  const detail = mode === 'blank' ? '' : ((value && value.detail) || '');
  const detailOption = options.find((o) => o.detail);

  const inline = options.length <= 3 && options.every((o) => (o.label || '').length <= 16);
  const rowH = 22;
  const rows = inline ? 1 : options.length;

  const labelH = flow.measureText(question.label || '', { size: SIZE_QUESTION, lineHeight: LINE_QUESTION });
  const detailH = detailOption ? 46 : 0;
  flow.ensure(labelH + 8 + rows * rowH + detailH);

  flow.text(question.label || '', {
    size: question.emphasis ? SIZE_QUESTION + 1 : SIZE_QUESTION,
    lineHeight: LINE_QUESTION,
    colour: question.emphasis ? NAVY : SLATE,
    bold: !!question.emphasis,
  });
  flow.move(6);

  const group = flow.form.createRadioGroup(flow.uniqueName(question.key));
  const top = flow.y;
  options.forEach((opt, i) => {
    const x = inline ? MARGIN_L + i * (CONTENT_W / options.length) : MARGIN_L;
    const y = inline ? top - CHECK_BOX : top - i * rowH - CHECK_BOX;
    group.addOptionToPage(opt.key, flow.page, {
      x, y, width: CHECK_BOX, height: CHECK_BOX,
      borderColor: BORDER, borderWidth: 0.9, backgroundColor: WHITE,
    });
    flow.page.drawText(toWinAnsi(opt.label), {
      x: x + CHECK_BOX + 8, y: y + 1.5, size: SIZE_QUESTION, font: flow.font, color: SLATE,
    });
  });
  if (selected && options.some((o) => o.key === selected)) {
    try { group.select(selected); } catch (_) { /* an unknown key simply stays unselected */ }
  }
  flow.move(rows * rowH + 4);

  if (detailOption) {
    const h = 30;
    flow.ensure(h + 14);
    flow.page.drawText(toWinAnsi(detailOption.detailLabel || 'Details'), {
      x: MARGIN_L, y: flow.y - SIZE_LABEL, size: SIZE_LABEL, font: flow.font, color: MUTED,
    });
    flow.move(SIZE_LABEL + 4);
    drawLineField(flow, {
      name: flow.uniqueName(`${question.key}__detail`),
      value: detail,
      x: MARGIN_L, y: flow.y - h, width: CONTENT_W, height: h,
    });
    flow.move(h + 8);
  }
}

/**
 * The rating grid. Every score is a labelled radio option inside a row-scoped
 * group, so "Communication — 3" is unambiguous on paper, in a screen reader
 * and in a PDF reader, and no row can hold two scores at once.
 */
function renderRatings(flow, question, value, mode) {
  const scale = question.scale || tpl.RATING_SCALE;
  const rows = question.rows || [];
  const scores = mode === 'blank' ? {} : (value && typeof value === 'object' ? value : {});

  const rowH = 23;
  const guideH = question.guide ? 20 : 0;
  const headH = 18;
  flow.ensure(headH + rows.length * rowH + guideH + 10);

  // Column header: the numbers, once, above the grid.
  const labelColW = 190;
  const gridX = MARGIN_L + labelColW;
  const stepW = (CONTENT_W - labelColW) / scale.length;

  scale.forEach((n, i) => {
    const label = String(n);
    const w = flow.bold.widthOfTextAtSize(label, SIZE_LABEL);
    flow.page.drawText(label, {
      x: gridX + i * stepW + (CHECK_BOX - w) / 2 + 1,
      y: flow.y - SIZE_LABEL,
      size: SIZE_LABEL, font: flow.bold, color: MUTED,
    });
  });
  flow.move(headH);

  rows.forEach((row) => {
    flow.ensure(rowH);
    const y = flow.y - CHECK_BOX;
    flow.page.drawText(toWinAnsi(row.label), {
      x: MARGIN_L, y: y + 1.5, size: SIZE_QUESTION, font: flow.font, color: SLATE,
    });
    const group = flow.form.createRadioGroup(flow.uniqueName(`${question.key}__${row.key}`));
    scale.forEach((n, i) => {
      group.addOptionToPage(`${n}`, flow.page, {
        x: gridX + i * stepW, y, width: CHECK_BOX, height: CHECK_BOX,
        borderColor: BORDER, borderWidth: 0.9, backgroundColor: WHITE,
      });
    });
    const chosen = Number(scores[row.key]);
    if (Number.isFinite(chosen) && scale.includes(chosen)) {
      try { group.select(String(chosen)); } catch (_) { /* leave unselected */ }
    }
    flow.move(rowH);
  });

  if (question.guide) {
    flow.move(4);
    flow.text(`Rating guide: ${question.guide}`, {
      size: SIZE_GUIDE, lineHeight: LINE_GUIDE, colour: MUTED, italic: true,
    });
  }
  flow.move(6);
}

function renderQuestion(flow, question, responses, mode) {
  const value = (responses || {})[question.key];
  switch (question.type) {
    case 'checkboxes': return renderCheckboxes(flow, question, value, mode);
    case 'choice':     return renderChoice(flow, question, value, mode);
    case 'ratings':    return renderRatings(flow, question, value, mode);
    case 'text':
    case 'date':
    case 'longtext':
    default:           return renderNarrative(flow, question, value, mode);
  }
}

