/**
 * Place one multiline answer field.
 *
 * `lines` is already wrapped and already pessimistic (see MEASURE_INSET), so
 * the box below is sized from a line count pdf-lib cannot exceed. The field's
 * value is the FULL chunk text — the appearance is what the box shows, /V is
 * what the document holds.
 */
function drawAnswerField(flow, { name, lines, value, x, width, height }) {
  const field = flow.form.createTextField(name);
  field.enableMultiline();
  if (value) field.setText(toWinAnsi(value));
  field.addToPage(flow.page, {
    x,
    y: flow.y - height,
    width,
    height,
    borderColor: BORDER,
    borderWidth: 0.7,
    backgroundColor: WHITE,
    textColor: SLATE,
    font: flow.font,
  });
  // AFTER addToPage: the /DA entry a font size is written into does not exist
  // until the widget does. The size then fixes the appearance at the one this
  // layout was measured against — left on auto, pdf-lib would shrink the text
  // to fit its own idea of the box and the document would drift out of step
  // with the portal. The final updateFieldAppearances() redraws at this size.
  field.setFontSize(SIZE_ANSWER);
  void lines;
  return field;
}

function drawLineField(flow, { name, value, x, y, width, height }) {
  const field = flow.form.createTextField(name);
  if (value) field.setText(toWinAnsi(value));
  field.addToPage(flow.page, {
    x, y, width, height,
    borderColor: BORDER,
    borderWidth: 0.7,
    backgroundColor: WHITE,
    textColor: SLATE,
    font: flow.font,
  });
  field.setFontSize(SIZE_LINE_FIELD);
  return field;
}

function drawCheckBox(flow, { name, checked, x, y, size = CHECK_BOX }) {
  const box = flow.form.createCheckBox(name);
  box.addToPage(flow.page, {
    x, y, width: size, height: size,
    borderColor: BORDER, borderWidth: 0.9, backgroundColor: WHITE,
  });
  if (checked) box.check();
  return box;
}

