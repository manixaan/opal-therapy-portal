function renderTitleBlock(flow, template) {
  flow.text(template.documentTitle || template.name, {
    size: SIZE_TITLE, lineHeight: SIZE_TITLE * 1.2, colour: NAVY,
  });
  flow.move(6);
  if (template.summary) {
    flow.text(template.summary, { size: SIZE_INTRO, lineHeight: SIZE_INTRO * 1.4, colour: MUTED });
  }
  flow.move(14);
}

/**
 * The candidate panel — the grey block at the head of the source template.
 * In 'populated' mode the values are already in the fields but the fields stay
 * editable, because an interviewer correcting a spelling should not have to
 * return to the portal.
 */
function renderCandidatePanel(flow, header, mode) {
  const cellH = 24;
  const panelH = 2 * (SIZE_LABEL + 4 + cellH) + 30;
  flow.ensure(panelH);

  const top = flow.y;
  flow.page.drawRectangle({
    x: MARGIN_L - 12, y: top - panelH, width: CONTENT_W + 24, height: panelH, color: PANEL,
  });

  const colW = (CONTENT_W - 20) / 2;
  const cells = [
    { key: 'candidate_name', label: 'Candidate name', value: header.candidateName },
    { key: 'interview_date', label: 'Interview date', value: header.interviewDate },
    { key: 'interviewers', label: 'Interviewer(s)', value: header.interviewers },
    { key: 'role_position', label: 'Role / position', value: header.position },
  ];

  cells.forEach((cell, i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const x = MARGIN_L + col * (colW + 20);
    const labelY = top - 15 - row * (SIZE_LABEL + 6 + cellH);
    flow.page.drawText(toWinAnsi(cell.label), {
      x, y: labelY, size: SIZE_LABEL, font: flow.font, color: MUTED,
    });
    drawLineField(flow, {
      name: flow.uniqueName(cell.key),
      value: mode === 'blank' ? '' : cell.value,
      x, y: labelY - 5 - cellH, width: colW, height: cellH,
    });
  });

  flow.move(panelH + 16);
}

function renderSectionBar(flow, section) {
  // A heading alone at the foot of a page is a broken document; keep it with
  // at least the first 40pt of whatever follows.
  flow.ensure(SECTION_BAR_H + 46);
  const y = flow.y - SECTION_BAR_H;
  flow.page.drawRectangle({
    x: MARGIN_L - 12, y, width: CONTENT_W + 24, height: SECTION_BAR_H, color: TEAL,
  });
  flow.page.drawText(toWinAnsi(`${section.number}. ${section.title}`), {
    x: MARGIN_L + 4, y: y + (SECTION_BAR_H - SIZE_SECTION) / 2 + 1.5,
    size: SIZE_SECTION, font: flow.font, color: WHITE,
  });
  flow.move(SECTION_BAR_H + 14);
}

function renderSignoff(flow, fields, responses, mode, header) {
  const cellH = 26;
  flow.ensure(SIZE_LABEL + 6 + cellH + 10);
  const colW = (CONTENT_W - 20) / 2;
  const top = flow.y;
  fields.forEach((f, i) => {
    const x = MARGIN_L + i * (colW + 20);
    flow.page.drawText(toWinAnsi(f.label), {
      x, y: top - SIZE_LABEL, size: SIZE_LABEL, font: flow.font, color: MUTED,
    });
    const typed = (responses || {})[f.key];
    const value = mode === 'blank'
      ? ''
      // An untyped sign-off falls back to the record's own interviewer/date
      // rather than printing blank; anything typed always wins.
      : (typed || (f.fallback && header ? header[f.fallback] : '') || '');
    drawLineField(flow, {
      name: flow.uniqueName(f.key),
      value,
      x, y: top - SIZE_LABEL - 6 - cellH, width: colW, height: cellH,
    });
  });
  flow.move(SIZE_LABEL + 6 + cellH + 10);
}

/**
 * The provenance strip on a populated document: who conducted it, what state
 * it is in, and whether it was edited after being declared complete. A printed
 * recruitment record that does not say this is not a record.
 */
function renderProvenance(flow, header) {
  const bits = [];
  if (header.status) bits.push(`Status: ${header.status}`);
  if (header.createdByName) bits.push(`Created by ${header.createdByName}`);
  if (header.completedAtText) bits.push(`Completed ${header.completedAtText}`);
  if (header.postCompletionEdits) {
    bits.push(`Edited after completion (${header.postCompletionEdits}${header.postCompletionEdits === 1 ? ' time' : ' times'})`);
  }
  if (header.generatedAtText) bits.push(`Generated ${header.generatedAtText}`);
  if (!bits.length) return;
  flow.move(4);
  flow.text(bits.join('  ·  '), { size: SIZE_GUIDE, lineHeight: LINE_GUIDE, colour: MUTED });
  flow.move(10);
}

