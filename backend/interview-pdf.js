/**
 * Build a download filename that is safe in a Content-Disposition header, on
 * every filesystem the practice uses, and readable by a person filing it.
 * Path separators, quotes, control characters and leading dots cannot survive.
 */
/**
 * Latin letters NFKD does not decompose.
 *
 * Normalising to NFKD splits e-acute into "e" plus a combining accent, which
 * the strip below then removes — but Ø, Æ, Ð, Þ, ß and Ł are single
 * indivisible letters, so NFKD leaves them whole and the strip deletes them
 * outright. Without this map, Renée Müller-Ødegård files as "Muller_degard".
 */
const FILENAME_FOLD = {
  'Ø': 'O', 'ø': 'o', 'Æ': 'AE', 'æ': 'ae', 'Œ': 'OE', 'œ': 'oe',
  'Đ': 'D', 'đ': 'd', 'Ð': 'D', 'ð': 'd', 'Þ': 'Th', 'þ': 'th',
  'ß': 'ss', 'Ł': 'L', 'ł': 'l', 'Ħ': 'H', 'ħ': 'h',
  'Ŧ': 'T', 'ŧ': 't', 'Ŋ': 'N', 'ŋ': 'n', 'İ': 'I', 'ı': 'i', 'ſ': 's',
};

function sanitiseFilenamePart(value, max = 60) {
  // Straight from the raw value, NOT via toWinAnsi: a filename wants the
  // letters transliteration would otherwise expand ('[yes]' for a tick).
  return String(value === null || value === undefined ? '' : value)
    .replace(/[ØøÆæŒœĐđÐðÞþßŁłĦħŦŧŊŋİıſ]/g, (c) => FILENAME_FOLD[c])
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, max) || 'Unnamed';
}

function blankFilename(template) {
  const stem = template.filenameStem
    || `Opal_Therapy_${sanitiseFilenamePart(template.name)}_Template`;
  return `${sanitiseFilenamePart(stem, 120)}.pdf`;
}

function recordFilename(template, record) {
  const who = sanitiseFilenamePart(record.candidate_name || 'Candidate', 50);
  const when = (() => {
    const d = record.interview_date ? new Date(record.interview_date) : new Date(record.created_at || Date.now());
    return isNaN(d.getTime()) ? 'undated' : d.toISOString().slice(0, 10);
  })();
  const stem = template.key === 'ot-interview'
    ? 'Opal_Therapy_OT_Interview'
    : `Opal_Therapy_${sanitiseFilenamePart(template.name, 60)}`;
  return `${stem}_${who}_${when}.pdf`;
}

