function statusLabel(status) {
  return ({
    draft: 'Draft', in_progress: 'In Progress', completed: 'Completed', archived: 'Archived',
  })[status] || status || '';
}

function formatDate(value) {
  if (!value) return '';
  const d = value instanceof Date ? value : new Date(value);
  if (isNaN(d.getTime())) return String(value);
  return d.toLocaleDateString('en-AU', { day: '2-digit', month: 'short', year: 'numeric', timeZone: 'UTC' });
}

function formatDateTime(value) {
  if (!value) return '';
  const d = value instanceof Date ? value : new Date(value);
  if (isNaN(d.getTime())) return '';
  return d.toLocaleString('en-AU', {
    day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: 'UTC',
  });
}

/**
 * Render an interview document.
 *
 * @param {object}  opts
 * @param {object}  opts.template   a template or a stored template_schema snapshot
 * @param {string} [opts.mode]      'blank' | 'populated'   (default 'blank')
 * @param {object} [opts.record]    the interview record, for 'populated'
 * @returns {Promise<{ bytes: Buffer, pageCount: number, fieldCount: number }>}
 */
async function renderInterviewPdf({ template, mode = 'blank', record = null } = {}) {
  if (!template || !Array.isArray(template.sections)) {
    throw new Error('renderInterviewPdf: a template with sections is required');
  }

  const pdf = await PDFDocument.create();
  const fonts = {
    regular: await pdf.embedFont(StandardFonts.Helvetica),
    bold: await pdf.embedFont(StandardFonts.HelveticaBold),
    italic: await pdf.embedFont(StandardFonts.HelveticaOblique),
  };

  const populated = mode === 'populated' && record;
  const responses = populated ? { ...(record.responses || {}) } : {};
  if (populated) {
    // Ratings and recommendation live in their own columns; the renderer only
    // knows the question grammar, so they are merged back under their keys.
    const index = tpl.questionIndex(template);
    for (const [key, q] of index) {
      if (q.type === 'ratings' && record.ratings) responses[key] = record.ratings;
      if (q.type === 'choice' && q.emphasis && record.recommendation !== undefined && record.recommendation !== null) {
        responses[key] = { option: record.recommendation, detail: '' };
      }
    }
  }

  const header = populated ? {
    candidateName: record.candidate_name || '',
    position: record.position || '',
    interviewDate: formatDate(record.interview_date),
    interviewers: record.interviewers || '',
    status: statusLabel(record.status),
    createdByName: record.created_by_name || '',
    completedAtText: formatDateTime(record.completed_at),
    postCompletionEdits: Number(record.post_completion_edits) || 0,
    generatedAtText: formatDateTime(new Date()),
  } : {
    candidateName: '', position: '', interviewDate: '', interviewers: '',
  };

  const flow = new Flow(pdf, fonts, {
    footer: template.documentFooter || `OPAL THERAPY | ${(template.name || 'INTERVIEW').toUpperCase()}`,
  });

  renderTitleBlock(flow, template);
  if (populated) renderProvenance(flow, header);
  renderCandidatePanel(flow, header, mode);

  template.sections.forEach((section) => {
    renderSectionBar(flow, section);
    (section.questions || []).forEach((question) => {
      renderQuestion(flow, question, responses, mode);
      flow.move(4);
    });
    if (Array.isArray(section.signoff) && section.signoff.length) {
      renderSignoff(flow, section.signoff, responses, mode, header);
    }
    flow.move(8);
  });

  flow.finish();

  // Regenerate every appearance with the document's own font so a reader that
  // trusts the stored appearance shows the same text as one that rebuilds it.
  try { flow.form.updateFieldAppearances(fonts.regular); } catch (_) { /* appearances stay as built */ }

  const bytes = Buffer.from(await pdf.save({ updateFieldAppearances: false }));
  return { bytes, pageCount: flow.pages.length, fieldCount: flow.form.getFields().length };
}

