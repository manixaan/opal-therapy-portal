//  The flowing document
// ─────────────────────────────────────────────────────────────────────────────

class Flow {
  constructor(pdf, fonts, meta) {
    this.pdf = pdf;
    this.form = pdf.getForm();
    this.font = fonts.regular;
    this.bold = fonts.bold;
    this.italic = fonts.italic;
    this.meta = meta;              // { footer }
    this.pages = [];
    this.page = null;
    this.y = 0;
    this.usedNames = new Set();
    this.newPage();
  }

  newPage() {
    const page = this.pdf.addPage([PAGE_W, PAGE_H]);
    page.drawRectangle({ x: 0, y: PAGE_H - BAND_H, width: PAGE_W, height: BAND_H, color: TEAL });
    this.pages.push(page);
    this.page = page;
    this.y = CONTENT_TOP;
    return page;
  }

  /** Room left on the current page for content. */
  get available() {
    return this.y - CONTENT_BOTTOM;
  }

  /** Ensure `height` of room, starting a page if not. Returns true if it broke. */
  ensure(height) {
    if (this.available >= height) return false;
    this.newPage();
    return true;
  }

  move(dy) {
    this.y -= dy;
  }

  /** A unique AcroForm name, so a split answer's parts never collide. */
  uniqueName(base) {
    let name = fieldName(base);
    let n = 2;
    while (this.usedNames.has(name)) { name = `${fieldName(base)}_${n}`; n += 1; }
    this.usedNames.add(name);
    return name;
  }

  text(value, opts = {}) {
    const size = opts.size || SIZE_QUESTION;
    const font = opts.bold ? this.bold : (opts.italic ? this.italic : this.font);
    const colour = opts.colour || SLATE;
    const lineHeight = opts.lineHeight || (size * 1.28);
    const width = opts.width || CONTENT_W;
    const x = opts.x === undefined ? MARGIN_L : opts.x;
    const lines = wrapText(value, font, size, width);

    for (const line of lines) {
      this.ensure(lineHeight);
      this.page.drawText(line, { x, y: this.y - size, size, font, color: colour });
      this.move(lineHeight);
    }
    return lines.length;
  }

  /** Height a text block would take, without drawing it. */
  measureText(value, opts = {}) {
    const size = opts.size || SIZE_QUESTION;
    const font = opts.bold ? this.bold : (opts.italic ? this.italic : this.font);
    const lineHeight = opts.lineHeight || (size * 1.28);
    const width = opts.width || CONTENT_W;
    return wrapText(value, font, size, width).length * lineHeight;
  }

  /** Paint the footer rule, caption and page number on every page. */
  finish() {
    const total = this.pages.length;
    this.pages.forEach((page, i) => {
      page.drawLine({
        start: { x: MARGIN_L, y: FOOTER_RULE_Y },
        end: { x: PAGE_W - MARGIN_R, y: FOOTER_RULE_Y },
        thickness: 0.6,
        color: BORDER,
      });
      page.drawText(toWinAnsi(this.meta.footer), {
        x: MARGIN_L, y: FOOTER_TEXT_Y, size: SIZE_FOOTER, font: this.font, color: NAVY,
      });
      const label = `Page ${i + 1} of ${total}`;
      const w = this.font.widthOfTextAtSize(label, SIZE_FOOTER);
      page.drawText(label, {
        x: PAGE_W - MARGIN_R - w, y: FOOTER_TEXT_Y, size: SIZE_FOOTER, font: this.font, color: MUTED,
      });
    });
  }
}

